globalThis.MorYaS05AddToBasket =
    function(runtimeScene) {

        // ==================================================
        // STATE + SESSION
        // ==================================================

        const state =
            globalThis.MorYaS05State;


        const session =
            globalThis.MorYaCaseSession ||
            {};


        globalThis.MorYaCaseSession =
            session;


        // ==================================================
        // VALIDATE CURRENT STATE
        // ==================================================

        if (
            !state ||
            state.inspectOpen !== true ||
            state.partConfirmOpen !== true
        ) {

            return;
        }


        if (
            Date.now() <
            state.partConfirmInputLockedUntil
        ) {

            return;
        }


        // ==================================================
        // CURRENT HERB
        // ==================================================

        const herb =
            state.herbConfigs?.[
                state.currentHerbId
            ];


        if (
            !herb ||
            !state.selectedPartId
        ) {

            return;
        }


        // ==================================================
        // HARVEST MODE BY PLANT PART
        //
        // ไม่ตรวจชื่อสมุนไพร
        // ตรวจเฉพาะชนิดส่วนพืช
        // ==================================================

        const HARVEST_MODE_BY_PART = {

            // ------------------------------------------
            // UNDERGROUND PARTS
            // ------------------------------------------

            ROOT:
                "DIG",

            RHIZOME:
                "DIG",


            // ------------------------------------------
            // LEAF PARTS
            // ------------------------------------------

            LEAF:
                "PLUCK",

            LEAFLET:
                "PLUCK",

            COMPOUND_LEAF:
                "PLUCK",


            // ------------------------------------------
            // STEM / BASE / SHEATH PARTS
            // ------------------------------------------

            STEM:
                "CUT",

            PSEUDOSTEM:
                "CUT",

            BASE:
                "CUT",

            LEAF_SHEATH:
                "CUT",

            SHEATH:
                "CUT",

            BRANCH:
                "CUT"
        };


        // ==================================================
        // SCENE BY HARVEST MODE
        // ==================================================

        const HARVEST_SCENE_BY_MODE = {

            DIG:
                "S05A_HarvestMinigame",

            PLUCK:
                "S05B_PluckHarvest",

            CUT:
                "S05C_CutHarvest"
        };


        // ==================================================
        // RESOLVE HARVEST MODE
        // ==================================================

        const harvestMode =
            HARVEST_MODE_BY_PART[
                state.selectedPartId
            ] ||
            "";


        const harvestScene =
            HARVEST_SCENE_BY_MODE[
                harvestMode
            ] ||
            "";


        console.log(
            "S05 HARVEST ROUTER:",
            {
                herb:
                    herb.herbId,

                herbName:
                    herb.nameTh,

                part:
                    state.selectedPartId,

                partName:
                    state.selectedPartNameTh,

                mode:
                    harvestMode,

                scene:
                    harvestScene
            }
        );


        // ==================================================
        // GENERIC HARVEST MINIGAME ROUTE
        //
        // ถ้ามี harvestMode
        // ให้เข้ามินิเกมตามส่วนพืชทันที
        // ==================================================

        if (
            harvestMode !== "" &&
            harvestScene !== ""
        ) {

            // ==================================================
            // SAVE HARVEST TARGET
            // ==================================================

            session.s05_harvest_herb_id =
                herb.herbId;


            session.s05_harvest_herb_name_th =
                herb.nameTh;


            session.s05_harvest_part_id =
                state.selectedPartId;


            session.s05_harvest_part_name_th =
                state.selectedPartNameTh;


            session.s05_harvest_mode =
                harvestMode;


            session.s05_harvest_completed =
                false;


            session.s05_harvest_started_at =
                Date.now();


            session.s05_harvest_return_scene =
                "S05_Intervention";


            session.s05_open_preparation_on_return =
                false;


            session.next_care_phase =
                "HARVEST_MINIGAME";


            // ==================================================
            // CLOSE INSPECT / PART CONFIRM
            // ==================================================

            hideInspect();

            hideConfirm();


            state.inspectOpen =
                false;


            state.partConfirmOpen =
                false;


            // ==================================================
            // PREVENT OTHER INPUT DURING SCENE TRANSITION
            // ==================================================

            state.harvestTransitionActive =
                true;


            state.basketReviewOpen =
                false;


            state.basketInputLockedUntil =
                Date.now() + 1000;


            state.gardenInputLockedUntil =
                Date.now() + 1000;


            // ==================================================
            // FORCE HIDE BASKET REVIEW
            //
            // ป้องกัน mouse release เดิมไปเปิด Basket Review
            // ==================================================

            [
                "Panel_BasketReview",
                "Txt_BasketReview",
                "Btn_BasketContinue",
                "Btn_BasketChange"
            ]
            .forEach(name => {

                runtimeScene
                    .getObjects(name)
                    .forEach(obj => {

                        obj.hide(
                            true
                        );
                    });
            });


            // ==================================================
            // DEBUG
            // ==================================================

            console.log(
                "S05 -> HARVEST MINIGAME:",
                {
                    herb:
                        session
                            .s05_harvest_herb_id,

                    herbName:
                        session
                            .s05_harvest_herb_name_th,

                    part:
                        session
                            .s05_harvest_part_id,

                    partName:
                        session
                            .s05_harvest_part_name_th,

                    mode:
                        session
                            .s05_harvest_mode,

                    scene:
                        harvestScene
                }
            );


            // ==================================================
            // GO TO HARVEST MINIGAME
            // ==================================================

            gdjs.evtTools.runtimeScene
                .replaceScene(
                    runtimeScene,
                    harvestScene,
                    false
                );


            return;
        }


        // ==================================================
        // DIRECT BASKET
        //
        // ใช้เฉพาะส่วนพืชที่ยังไม่มี harvest minigame
        //
        // เช่น:
        // FLOWER
        // SEED
        // อื่น ๆ
        // ==================================================

        state.basketHerbId =
            herb.herbId;


        state.basketHerbNameTh =
            herb.nameTh;


        state.basketPartId =
            state.selectedPartId;


        state.basketPartNameTh =
            state.selectedPartNameTh;


        // ==================================================
        // SAVE TO SESSION
        // ==================================================

        session.s05_basket_herb_id =
            state.basketHerbId;


        session.s05_basket_herb_name_th =
            state.basketHerbNameTh;


        session.s05_basket_part_id =
            state.basketPartId;


        session.s05_basket_part_name_th =
            state.basketPartNameTh;


        // ป้องกันค่า harvest เก่าค้าง
        session.s05_harvest_mode =
            "";


        session.s05_harvest_completed =
            false;


        session.s05_open_preparation_on_return =
            false;


        state.harvestTransitionActive =
            false;


        // ==================================================
        // REFRESH BASKET
        // ==================================================

        refreshBasketStatus();


        // ==================================================
        // CLOSE INSPECT
        // ==================================================

        hideInspect();

        hideConfirm();


        state.inspectOpen =
            false;


        state.partConfirmOpen =
            false;


        state.currentHerbId =
            "";


        state.gardenInputLockedUntil =
            Date.now() + 300;


        console.log(
            "S05 DIRECT BASKET:",
            {
                herb:
                    state.basketHerbId,

                herbName:
                    state.basketHerbNameTh,

                part:
                    state.basketPartId,

                partName:
                    state.basketPartNameTh
            }
        );
    };
