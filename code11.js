    globalThis.MorYaS05ChoosePart =
        function(
            runtimeScene,
            slot
        ) {

            const state =
                globalThis.MorYaS05State;

            if (
                !state ||
                state.inspectOpen !== true
            ) {
                return;
            }


            if (
                state.partConfirmOpen === true
            ) {
                return;
            }


            if (
                Date.now() <
                state.partInputLockedUntil
            ) {
                return;
            }


            const herb =
                state.herbConfigs?.[
                    state.currentHerbId
                ];


            if (!herb) {
                return;
            }


            const part =
                herb.parts.find(
                    item =>
                        item.slot === slot
                );


            if (!part) {
                return;
            }


            state.selectedPartSlot =
                slot;

            state.selectedPartId =
                part.partId;

            state.selectedPartNameTh =
                part.partNameTh;

            state.partConfirmOpen =
                true;

            state.partConfirmInputLockedUntil =
                Date.now() + 250;


            hideMany(
                confirmObjects,
                false
            );


            setTextSafe(
                "Txt_PartConfirm",

                "คุณเลือกส่วนของพืช:\n\n" +
                herb.nameTh +
                "\n" +
                part.partNameTh
            );


            setTextSafe(
                "Btn_AddToBasket",
                "[ ใส่ตะกร้า ]"
            );


            setTextSafe(
                "Btn_SelectAnotherPart",
                "[ เลือกส่วนใหม่ ]"
            );


            console.log(
                "S05 SELECT PART:",
                {
                    herb:
                        state.currentHerbId,

                    slot:
                        slot,

                    part:
                        part.partId
                }
            );
        };


